// ── Held tool sprites ───────────────────────────────────────────────────────
// Each tool has a silhouette (axe/pickaxe/sword) plus a head/guard colour
// and scale. Wooden tiers are wood-toned all the way through — head, guard,
// and handle — so nothing on them reads as stone or metal; stone tiers reuse
// the same shapes with a heavier, gray head, and gold tiers reuse them again
// with a gold head, so each upgrade reads as the same tool in a new
// material rather than an unrelated item.

type ToolShape = 'axe' | 'pickaxe' | 'sword' | 'rod' | 'hoe' | 'wateringcan';
interface ToolVisual { shape: ToolShape; head: string; guard: string; scale: number }

