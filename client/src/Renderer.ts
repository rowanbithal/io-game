// ── Plains ground clutter ───────────────────────────────────────────────────
// Flowers growing in patches — purely decorative, no server data or gameplay
// effect, same deal as a rock's pebbles: a stable per-cell hash decides
// whether a roll site gets one, generated once and cached. Drawn right after
// the base grass tile and before everything else, so trees, rocks,
// structures and lakes occlude it exactly the way they already occlude the
// grass beneath — no explicit "don't overlap a resource" logic needed.
//
// Fallen leaves are NOT here, despite sharing leafCells with the thing that
// is: a leaf scattered loose in open grass with no tree anywhere nearby
// doesn't read as a fallen leaf, just as a green fleck. They only appear
// anchored to their source, as litter around an actual tree's crown (see
// treeLeafLitterClusters). Loose stones are the same story, anchored to
// actual rock deposits (see rockPebbles) rather than sprinkled at random here.

/** World units between roll sites — coarser than BLOCK so clutter reads as scattered incident, not a woven texture. */
const CLUTTER_CELL = 38;
/** Smaller than the main sprite grid (BLOCK): clutter should read as delicate detail, not another chunky resource. */
const CLUTTER_BLOCK = BLOCK * 0.6;
const CLUTTER_SALT = 211;

// Where flowers are allowed to grow at all — a coarse noise field read the
// same way other lattice-backed textures on this map are, so blooms cluster
// into a few irregular meadow patches across the map instead of being
// sprinkled evenly everywhere, the way real wildflowers actually grow in
// clumps rather than one at a time.
//
// LATTICE_SIZE has to be large enough that LATTICE_SIZE * PATCH_SCALE *
// CLUTTER_CELL — the world-unit period the whole pattern repeats at, same as
// any lattice tiling — comfortably exceeds MAP_SIZE (4000). A fine noise
// texture like the grass tile can get away with repeating well
// inside the map, because at that scale nobody can tell one 10-unit speckle
// from an identical one 3000 units away. A patch here is ~900 world units of
// distinctly-shaped meadow — closer to the size of a lake than a grass
// speckle — so the same undersized lattice that's invisible for fog would
// read as the exact same meadow copy-pasted across the map. 17 puts the
// period at ~5800, longer than the map in both axes, so no repeat is
// reachable at all.
const FLOWER_PATCH_LATTICE_SIZE = 17;
const FLOWER_PATCH_LATTICE = buildLattice(FLOWER_PATCH_LATTICE_SIZE, mulberry32(CLUTTER_SALT + 900));
/** Clutter cells per lattice cell — ~340 world units, big enough to read as a real patch of meadow, not a single leaf-sized freckle. */
const FLOWER_PATCH_SCALE = 9;
/** Only the upper slice of the field becomes a patch (~17% of the plains) — most of it stays patch-free, so the ones that exist stand out. */
const FLOWER_PATCH_THRESHOLD = 0.76;
/** Fraction of roll sites inside a patch that get a flower — this is the "clump" part of a flower clump. */
const CLUTTER_MEADOW_DENSITY = 0.7;

interface ClutterPiece { cells: Cell[]; palette: Palette3 }

/** One of a few petal colors, paired with the same warm core every time — same idea as a real flower's fixed centre regardless of species. */
const FLOWER_PETAL_PALETTES: Palette3[] = [
  { light: P.flowerPetalWhiteLight, base: P.flowerPetalWhite, dark: P.flowerCore },
  { light: P.flowerPetalPinkLight, base: P.flowerPetalPink, dark: P.flowerCore },
  { light: P.flowerPetalBlueLight, base: P.flowerPetalBlue, dark: P.flowerCore },
];

/** A tiny five-cell bloom: one core cell plus four petals, nudged off-grid so it doesn't read as a perfect plus sign. */
function flowerCells(rng: () => number): Cell[] {
  const cells: Cell[] = [{ gx: 0, gy: 0, shade: 'dark' }]; // core
  const reach = 0.85;
  for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]] as const) {
    const jitter = 0.85 + rng() * 0.3;
    cells.push({ gx: dx * reach * jitter, gy: dy * reach * jitter, shade: 'base' });
  }
  // One petal catches the light — keeps a 5-cell bloom from reading as flat.
  cells[1 + Math.floor(rng() * 4)].shade = 'light';
  return cells;
}

/**
 * A tiny fallen leaf: two or three blades fanned from a shared root, darker
 * at the base, catching light at the tip — same shading idea wheatCells
 * uses. The one glyph shape scattered around a tree's own crown as litter
 * (see treeLeafLitterClusters); nothing outside that draws from it.
 */
function leafCells(rng: () => number): Cell[] {
  const cells: Cell[] = [];
  const bladeCount = 2 + Math.floor(rng() * 2);
  for (let i = 0; i < bladeCount; i++) {
    const lean = (rng() - 0.5) * 0.9 + (i - (bladeCount - 1) / 2) * 0.7;
    const length = 2 + Math.floor(rng() * 2);
    for (let j = 0; j < length; j++) {
      const shade: Shade = j === 0 ? 'dark' : j === length - 1 ? 'light' : 'base';
      cells.push({ gx: lean * (j + 1) * 0.35, gy: -j * 0.85, shade });
    }
  }
  return cells;
}

const clutterCache = new Map<number, ClutterPiece | null>();

/**
 * Deterministic per-cell roll, cached by the cell's own hash. Only rolls at
 * all inside a flower patch (see FLOWER_PATCH_LATTICE); outside one, nothing
 * — that's the whole mechanism keeping flowers confined to patches instead
 * of sprinkled evenly across the plains.
 */
function getClutterPiece(gx: number, gy: number): ClutterPiece | null {
  const seed = hashCell(gx, gy, CLUTTER_SALT);
  const cached = clutterCache.get(seed);
  if (cached !== undefined) return cached;

  const rng = mulberry32(seed);
  const inMeadow = sampleLattice(FLOWER_PATCH_LATTICE, FLOWER_PATCH_LATTICE_SIZE, FLOWER_PATCH_SCALE, gx, gy) > FLOWER_PATCH_THRESHOLD;

  const piece: ClutterPiece | null =
    inMeadow && rng() < CLUTTER_MEADOW_DENSITY
      ? { cells: flowerCells(rng), palette: FLOWER_PETAL_PALETTES[Math.floor(rng() * FLOWER_PETAL_PALETTES.length)] }
      : null;

  clutterCache.set(seed, piece);
  return piece;
}

// ── Sea beach clutter ────────────────────────────────────────────────────────
// Seashells and starfish scattered over the sand — the sea's answer to the
// flower patches above, but sparser and unpatched (every roll site on the
// beach gets an independent low-probability roll rather than being confined
// to a lattice of patches — a beach's shells wash up individually, not in
// meadow-sized clumps). Gating to the sand band itself is the caller's job
// (see drawBeachClutter), same as drawGroundClutter skips cells the forest
// floor would paint over anyway.

const BEACH_CLUTTER_SALT = 511;
/** Fraction of beach roll sites that get a shell or starfish at all — "occasional", not a carpet of them. */
const BEACH_CLUTTER_DENSITY = 0.05;

const SHELL_PALETTE: Palette3 = { light: P.shellLight, base: P.shell, dark: P.shellDark };
const STARFISH_PALETTE: Palette3 = { light: P.starfishLight, base: P.starfish, dark: P.starfishDark };

/** A tiny fluted scallop shell: a shadowed hinge point widening into a light-catching fan. */
function shellCells(rng: () => number): Cell[] {
  const cells: Cell[] = [
    { gx: 0, gy: -1, shade: 'base' },
    { gx: -1, gy: 0, shade: 'base' },
    { gx: 0, gy: 0, shade: 'dark' },
    { gx: 1, gy: 0, shade: 'base' },
    { gx: -0.5, gy: 1, shade: 'light' },
    { gx: 0.5, gy: 1, shade: 'light' },
  ];
  const ribs = [0, 1, 3];
  cells[ribs[Math.floor(rng() * ribs.length)]].shade = 'light';
  return cells;
}

/** A tiny five-armed starfish, built the same "core plus jittered points" way flowerCells is. */
function starfishCells(rng: () => number): Cell[] {
  const cells: Cell[] = [{ gx: 0, gy: 0, shade: 'dark' }];
  const armLen = 1.4;
  const tipIndices: number[] = [];
  for (let i = 0; i < 5; i++) {
    const angle = (i / 5) * Math.PI * 2 + rng() * 0.3;
    cells.push({ gx: Math.cos(angle) * armLen * 0.55, gy: Math.sin(angle) * armLen * 0.55, shade: 'base' });
    tipIndices.push(cells.length);
    cells.push({ gx: Math.cos(angle) * armLen, gy: Math.sin(angle) * armLen, shade: 'base' });
  }
  cells[tipIndices[Math.floor(rng() * tipIndices.length)]].shade = 'light';
  return cells;
}

const beachClutterCache = new Map<number, ClutterPiece | null>();

/** Deterministic per-cell roll for beach clutter — same caching/hashing deal as getClutterPiece, own salt so the two never roll in lockstep. */
function getBeachClutterPiece(gx: number, gy: number): ClutterPiece | null {
  const seed = hashCell(gx, gy, BEACH_CLUTTER_SALT);
  const cached = beachClutterCache.get(seed);
  if (cached !== undefined) return cached;

  const rng = mulberry32(seed);
  const piece: ClutterPiece | null =
    rng() < BEACH_CLUTTER_DENSITY
      ? rng() < 0.55
        ? { cells: shellCells(rng), palette: SHELL_PALETTE }
        : { cells: starfishCells(rng), palette: STARFISH_PALETTE }
      : null;

  beachClutterCache.set(seed, piece);
  return piece;
}

