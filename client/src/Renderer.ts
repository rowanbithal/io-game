/**
 * A single thin stick, `length` blocks long and only one block wide,
 * stepping diagonally by (dgx, dgy) per cell rather than running flat — the
 * fractional per-step drift means neighbouring cells overlap slightly,
 * which (like the wheat icon) reads as a loose, slightly irregular twig
 * instead of a ruler-straight bar. Cut ends and a mid-stick knot go dark;
 * everywhere else alternates light/base along its length for grain texture.
 */
function stickBar(cx: number, cy: number, length: number, dgx: number, dgy: number): Cell[] {
  const cells: Cell[] = [];
  const start = -(length - 1) / 2;
  const knotAt = Math.floor(length / 2);
  for (let i = 0; i < length; i++) {
    const isEnd = i === 0 || i === length - 1;
    const isKnot = i === knotAt;
    const shade: Shade = isEnd || isKnot ? 'dark' : i % 2 === 0 ? 'light' : 'base';
    cells.push({ gx: cx + (start + i) * dgx, gy: cy + (start + i) * dgy, shade });
  }
  return cells;
}

