/** A loose scatter of 3-5 blocks around a centre, the same "core plus jittered points" shape flowerCells/starfishCells use — a tumbling clump rather than a neat square. */
function sandClumpCells(rng: () => number): Cell[] {
  const cells: Cell[] = [];
  const count = 3 + Math.floor(rng() * 3);
  for (let i = 0; i < count; i++) {
    const angle = rng() * Math.PI * 2;
    const r = rng() * 1.3;
    const shade: Shade = rng() < 0.25 ? 'dark' : rng() < 0.7 ? 'base' : 'light';
    cells.push({ gx: Math.cos(angle) * r, gy: Math.sin(angle) * r, shade });
  }
  return cells;
}

/**
 * A ripple ring built from BLOCK cells at roughly `radius` from the local
 * origin — unlike the fish, a ring looks the same at any rotation, so this
 * stays genuinely pixel-grid-aligned with no rotation trade-off at all.
 */
function drawPixelRing(ctx: CanvasRenderingContext2D, radius: number, color: string): void {
  if (radius < BLOCK * 0.5) return;
  const thickness = BLOCK * 1.1;
  const reach = Math.ceil((radius + thickness) / BLOCK);
  const path = new Path2D();
  for (let gy = -reach; gy <= reach; gy++) {
    for (let gx = -reach; gx <= reach; gx++) {
      const cx = gx * BLOCK;
      const cy = gy * BLOCK;
      if (Math.abs(Math.hypot(cx, cy) - radius) > thickness / 2) continue;
      path.rect(cx - BLOCK / 2, cy - BLOCK / 2, BLOCK, BLOCK);
    }
  }
  ctx.fillStyle = color;
  ctx.fill(path);
}

/**
 * A fishing line as a row of small square dots stepped along the straight
 * path from (x1,y1) to (x2,y2), snapped to a `dotSize` grid — same "stay on
 * the pixel grid" approach as everything else, rather than an anti-aliased
 * stroke, which would be the one smooth diagonal line in an otherwise
 * all-blocky game.
 */
function drawPixelLine(
  ctx: CanvasRenderingContext2D,
  x1: number,
  y1: number,
  x2: number,
  y2: number,
  color: string,
  dotSize: number,
  spacing: number,
): void {
  const dx = x2 - x1;
  const dy = y2 - y1;
  const dist = Math.hypot(dx, dy);
  const steps = Math.max(1, Math.round(dist / spacing));
  const path = new Path2D();
  for (let i = 0; i <= steps; i++) {
    const t = i / steps;
    const x = x1 + dx * t;
    const y = y1 + dy * t;
    path.rect(
      Math.round(x / dotSize) * dotSize - dotSize / 2,
      Math.round(y / dotSize) * dotSize - dotSize / 2,
      dotSize,
      dotSize,
    );
  }
  ctx.fillStyle = color;
  ctx.fill(path);
}

