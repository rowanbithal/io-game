// ── Fireflies ────────────────────────────────────────────────────────────────
// Dark forest ambiance, and purely that — like the lake fish, they're
// simulated client-side only, never touch the server, and nothing in the
// game can collide with, harvest, or otherwise interact with them.
//
// Each one drifts around a fixed anchor point rather than free-roaming, so
// the swarm stays spread through the forest instead of slowly clumping, and
// so a firefly never wanders out onto the plains.

interface Firefly {
  ax: number; // anchor (the point it flits around), world coords
  ay: number;
  x: number; // current position, world coords
  y: number;
  angle: number;
  speed: number;
  drift: number; // how far from its anchor it's allowed to stray
  pulse: number; // 0..1 phase of its glow blink
  pulseSpeed: number;
}

// Tuned for roughly a dozen in view at once deep in the forest — enough to
// feel alive, few enough that each blink still reads as its own little light.
const FIREFLY_TARGET_COUNT = 110;
const FIREFLY_BLOCK = BLOCK / 2; // finer than the main grid — they're tiny points of light
/** Glow layers drawn under the core, outermost first: [half-extent in blocks, alpha scale]. */
const FIREFLY_GLOW_LAYERS: [number, number][] = [
  [2.5, 0.1],
  [1.5, 0.22],
];

/**
 * One firefly: a bright single-block core with a couple of dim blocky halos
 * around it. Square halos rather than round ones — at this size a circle
 * would need anti-aliasing to read as round at all, which is exactly what
 * the rest of the game's art avoids. Drawn additively by the caller, so the
 * halos read as light spilling onto what's behind them.
 */
function drawFireflyShape(ctx: CanvasRenderingContext2D, brightness: number): void {
  for (const [halfBlocks, alphaScale] of FIREFLY_GLOW_LAYERS) {
    const size = halfBlocks * 2 * FIREFLY_BLOCK;
    ctx.globalAlpha = brightness * alphaScale;
    ctx.fillRect(-size / 2, -size / 2, size, size);
  }
  ctx.globalAlpha = brightness;
  ctx.fillRect(-FIREFLY_BLOCK / 2, -FIREFLY_BLOCK / 2, FIREFLY_BLOCK, FIREFLY_BLOCK);
}

/**
 * A ripple ring built from BLOCK cells at roughly `radius` from the local
 * origin — unlike the fish, a ring looks the same at any rotation, so this
 * stays genuinely pixel-grid-aligned with no rotation trade-off at all.
 */
function drawPixelRing(ctx: CanvasRenderingContext2D, radius: number, color: string): void {
  if (radius < BLOCK * 0.5) return;
  const thickness = BLOCK * 1.1;
  const reach = Math.ceil((radius + thickness) / BLOCK);
  const path = new Path2D();
  for (let gy = -reach; gy <= reach; gy++) {
    for (let gx = -reach; gx <= reach; gx++) {
      const cx = gx * BLOCK;
      const cy = gy * BLOCK;
      if (Math.abs(Math.hypot(cx, cy) - radius) > thickness / 2) continue;
      path.rect(cx - BLOCK / 2, cy - BLOCK / 2, BLOCK, BLOCK);
    }
  }
  ctx.fillStyle = color;
  ctx.fill(path);
}

/**
 * A fishing line as a row of small square dots stepped along the straight
 * path from (x1,y1) to (x2,y2), snapped to a `dotSize` grid — same "stay on
 * the pixel grid" approach as everything else, rather than an anti-aliased
 * stroke, which would be the one smooth diagonal line in an otherwise
 * all-blocky game.
 */
function drawPixelLine(
  ctx: CanvasRenderingContext2D,
  x1: number,
  y1: number,
  x2: number,
  y2: number,
  color: string,
  dotSize: number,
  spacing: number,
): void {
  const dx = x2 - x1;
  const dy = y2 - y1;
  const dist = Math.hypot(dx, dy);
  const steps = Math.max(1, Math.round(dist / spacing));
  const path = new Path2D();
  for (let i = 0; i <= steps; i++) {
    const t = i / steps;
    const x = x1 + dx * t;
    const y = y1 + dy * t;
    path.rect(
      Math.round(x / dotSize) * dotSize - dotSize / 2,
      Math.round(y / dotSize) * dotSize - dotSize / 2,
      dotSize,
      dotSize,
    );
  }
  ctx.fillStyle = color;
  ctx.fill(path);
}

