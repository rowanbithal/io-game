// Dark wrap lashing a stone or wooden head to its haft — always this tone
// regardless of tier, since the binding is leather/cord either way.
const TOOL_BINDING = P.logDark;

/**
 * Draws a held tool at (toolX, toolY), `block` units per pixel. Used both
 * for the in-hand version (block = BLOCK, the world pixel size) and for HUD
 * icons (a smaller block, via drawToolIcon below) — same shapes either way,
 * so an icon always matches what the tool looks like equipped.
 */
function drawHeldTool(
  ctx: CanvasRenderingContext2D,
  { shape, head, guard, scale }: ToolVisual,
  toolX: number,
  toolY: number,
  block: number = BLOCK,
): void {
  const b = block * scale;

  if (shape === 'axe') {
    ctx.fillStyle = P.logLight;
    ctx.fillRect(toolX, toolY, b * 4.4, block);

    ctx.fillStyle = TOOL_BINDING;
    ctx.fillRect(toolX + b * 3.65, toolY - b * 0.15, b * 0.35, block + b * 0.3);

    // One-sided head: flush with the handle, flaring wider (and thicker)
    // as it steps away from it — a bit, not a symmetric double-bladed head.
    ctx.fillStyle = head;
    ctx.fillRect(toolX + b * 3.85, toolY - b * 1.5, b * 1.0, b * 1.5);
    ctx.fillRect(toolX + b * 3.6, toolY - b * 2.75, b * 1.6, b * 1.5);
    return;
  }

  if (shape === 'pickaxe') {
    ctx.fillStyle = P.logLight;
    ctx.fillRect(toolX, toolY, b * 4.2, block);

    ctx.fillStyle = TOOL_BINDING;
    ctx.fillRect(toolX + b * 3.55, toolY - b * 0.15, b * 0.3, block + b * 0.3);

    // Each point is a base block at the socket, then a tip block that
    // curls back toward the player (negative x, i.e. back over the haft)
    // as it reaches further out in y — an actual hook, like a real (or
    // Minecraft) pickaxe head, instead of a chevron pointing straight away.
    const socketX = toolX + b * 3.65;
    ctx.fillStyle = head;
    ctx.fillRect(socketX, toolY - b * 0.8, b * 0.9, b * 0.95);
    ctx.fillRect(socketX - b * 0.5, toolY - b * 1.5, b * 0.9, b * 0.95);
    ctx.fillRect(socketX, toolY - b * 0.15, b * 0.9, b * 0.95);
    ctx.fillRect(socketX - b * 0.5, toolY + b * 0.55, b * 0.9, b * 0.95);
    return;
  }

  if (shape === 'hoe') {
    ctx.fillStyle = P.logLight;
    ctx.fillRect(toolX, toolY, b * 4.4, block);

    ctx.fillStyle = TOOL_BINDING;
    ctx.fillRect(toolX + b * 3.65, toolY - b * 0.15, b * 0.35, block + b * 0.3);

    // A flat blade mounted crosswise at the tip, like a real hoe head —
    // distinct from the axe's angled wedge and the pickaxe's hooked points.
    ctx.fillStyle = head;
    ctx.fillRect(toolX + b * 3.9, toolY - b * 1.7, b * 1.6, b * 0.75);
    return;
  }

  if (shape === 'wateringcan') {
    // A squat can body with a raised front panel, a carry handle looping
    // over the top, and a spout angled out and down toward the tip.
    ctx.fillStyle = guard;
    ctx.fillRect(toolX, toolY - b * 0.5, b * 2.0, b * 2.0);

    ctx.fillStyle = head;
    ctx.fillRect(toolX + b * 0.25, toolY - b * 0.25, b * 1.5, b * 1.5);

    ctx.fillStyle = guard;
    ctx.fillRect(toolX + b * 0.5, toolY - b * 1.05, b * 1.0, b * 0.55); // handle loop
    ctx.fillRect(toolX + b * 1.85, toolY - b * 1.0, b * 1.5, b * 0.55); // spout
    ctx.fillRect(toolX + b * 3.15, toolY - b * 0.65, b * 0.55, b * 0.55); // spout tip
    return;
  }

  if (shape === 'rod') {
    // A long, thin pole — nothing else this shape-family draws is this
    // long or this narrow — with a grip near the hand and a small guide
    // ring at the tip the line runs through.
    const rodLen = b * 7.0;
    ctx.fillStyle = guard;
    ctx.fillRect(toolX, toolY - block * 0.1, b * 1.0, block * 1.2);

    ctx.fillStyle = P.logLight;
    ctx.fillRect(toolX + b * 0.8, toolY + block * 0.15, rodLen - b * 0.8, block * 0.6);

    ctx.fillStyle = head;
    ctx.fillRect(toolX + rodLen - b * 0.2, toolY, b * 0.5, block);
    return;
  }

  // Sword: pommel, hilt, crossguard, and a blade with a thin highlighted edge.
  ctx.fillStyle = guard;
  ctx.fillRect(toolX - b * 0.55, toolY - b * 0.1, b * 0.55, block + b * 0.2);

  ctx.fillStyle = P.logLight;
  ctx.fillRect(toolX, toolY, b * 1.5, block);

  ctx.fillStyle = guard;
  ctx.fillRect(toolX + b * 1.3, toolY - b * 0.65, b * 0.5, b * 2.3);

  ctx.fillStyle = head;
  ctx.fillRect(toolX + b * 1.9, toolY - b * 0.15, b * 3.6, b * 0.8);
  ctx.fillStyle = guard;
  ctx.fillRect(toolX + b * 1.9, toolY - b * 0.15, b * 3.6, b * 0.2);
}

// Each shape's rough footprint (in blocks, at scale 1), and where its centre
// actually falls within that footprint — used to place it at the origin for
// an icon instead of growing rightward from a hand position. Half-width is
// sized for the ROTATED icon (see drawToolIcon) — a 45°-rotated bounding
// box needs more room than the unrotated shape, so this is bigger than the
// shape's own unrotated half-width, with a small safety margin on top.
const TOOL_ICON_HALF_WIDTH: Record<ToolShape, number> = { axe: 3.5, pickaxe: 2.9, sword: 3.2, rod: 3.25, hoe: 3.5, wateringcan: 2.6 };
const TOOL_ICON_CENTER: Record<ToolShape, { x: number; y: number }> = {
  axe: { x: -2.6, y: 0.8 },
  pickaxe: { x: -2.275, y: 0 },
  sword: { x: -2.475, y: -0.5 },
  rod: { x: -3.65, y: -0.5 },
  hoe: { x: -2.6, y: 0.85 },
  wateringcan: { x: -1.6, y: 0.25 },
};

/**
 * Draws a held tool centred on the origin, tilted diagonally (head up-right,
 * handle down-left) for use as a HUD icon — same convention as Minecraft's
 * item icons, distinct from the straight-out-from-the-hand angle used for
 * the in-hand version (drawHeldTool itself is never rotated).
 */
export function drawToolIcon(ctx: CanvasRenderingContext2D, itemId: string, block: number = BLOCK): void {
  const visual = TOOL_VISUALS[itemId];
  if (!visual) return;
  const center = TOOL_ICON_CENTER[visual.shape];
  const b = block * visual.scale;
  ctx.save();
  ctx.rotate(-Math.PI / 4);
  drawHeldTool(ctx, visual, center.x * b, center.y * b, block);
  ctx.restore();
}

/** Half-width used to fit a tool icon into a HUD slot — see drawToolIcon. */
export function toolIconHalfBlocks(itemId: string): number {
  const visual = TOOL_VISUALS[itemId];
  return visual ? TOOL_ICON_HALF_WIDTH[visual.shape] * visual.scale : 2;
}

// ── Torch ────────────────────────────────────────────────────────────────────
// Worn in the off hand (see PlayerState.torch) rather than held like a tool,
// but drawn the same "silhouette plus a flame tip" way as the tools above —
// a short haft with a small flickering flame, reusing the campfire's own
// ember palette so the two flames read as the same kind of fire.

/**
 * Draws a held torch gripped at (x, y) — that point is the haft's own
 * vertical center at its near end, matching the hand block it's drawn into
 * (see drawPlayer), and the haft then runs outward along +x from there.
 * `block` units per pixel; used both for the in-hand version (block =
 * BLOCK) and for the HUD icon (a smaller block, via drawTorchIcon below),
 * same pattern as drawHeldTool/drawToolIcon.
 */
function drawHeldTorch(ctx: CanvasRenderingContext2D, x: number, y: number, block: number = BLOCK, now = 0): void {
  const b = block;

  // A stout, plain haft — noticeably thicker than the fishing rod's own
  // stick (see drawHeldTool's 'rod' shape) so a torch reads as something
  // gripped in a fist rather than a slender pole. No binding wrap: just the
  // one solid length of wood, vertically centered on the grip point.
  const haftLen = b * 2.7;
  const haftHeight = block * 1.1;
  ctx.fillStyle = P.logDark;
  ctx.fillRect(x, y - haftHeight / 2, haftLen, haftHeight);

  // Flame at the tip, flickering gently — same wobble shape as the
  // campfire light's own breathing (see Renderer.flicker), applied to the
  // flame's size here instead of an overlay's alpha. Both layers are
  // yellow/white (torchFlameYellow/torchFlameCore) rather than the
  // campfire's own orange embers — a torch flame reads hotter, yellower,
  // and tighter than the campfire's fire. Both squares are centered on the
  // same point, directly off the end of the haft, so the flame reads as one
  // concentric blob rather than a stack of off-axis layers.
  const flick = 0.85 + 0.15 * Math.sin(now / 90) * Math.sin(now / 37);
  const s = b * 1.15 * flick;
  const flameCX = x + haftLen;
  ctx.fillStyle = P.torchFlameYellow;
  ctx.fillRect(flameCX - s * 0.45, y - s * 0.55, s * 0.9, s * 1.1);
  ctx.fillStyle = P.torchFlameCore;
  ctx.fillRect(flameCX - s * 0.19, y - s * 0.23, s * 0.38, s * 0.46);
}

