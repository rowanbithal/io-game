// ── Harvest recoil ───────────────────────────────────────────────────────────
// A struck resource kicks back from whoever hit it and settles home again, so
// a landed swing reads as landed without needing a hit sound or a flash.
//
// It's driven purely by watching each resource's hp drop between snapshots
// rather than by any new server message, which gets two things for free:
// other players' swings animate exactly like your own, and a swing that
// legitimately does nothing animates nothing. That second one is what keeps a
// wooden pickaxe swung at gold looking as useless as it is — the server
// refuses the strike, the hp never moves, so the boulder never flinches.

/** How far a struck resource kicks back, in world units — a nudge, not a leap. */
const RESOURCE_RECOIL_DIST = 4.5;
/** Seconds from the strike landing to fully settled. */
const RESOURCE_RECOIL_DURATION = 0.26;
/**
 * Fraction of that spent travelling outward. Small on purpose: the knock away
 * should be near-instant and the return the part you actually read, the same
 * shape as something heavy being jolted and rocking back into place.
 */
const RESOURCE_RECOIL_ATTACK = 0.22;

/** Live recoil state for one resource, keyed by id in `resourceRecoil`. */
interface ResourceRecoil {
  hp: number; // hp at the previous snapshot, to spot a strike landing
  t: number; // seconds into the bounce; >= RESOURCE_RECOIL_DURATION means settled
  dx: number; // unit vector pointing away from whoever struck it
  dy: number;
}

// Low bushes/fungi that everything else (trees, rocks, wheat, gold) should
// always draw over, regardless of which one happens to sit at a lower
// screen y — a plain y-sort occasionally puts a berry bush "in front of" a
// tree trunk or boulder it's actually standing beside, which reads as the
// bush floating on top of it. See resourceDrawOrder below.
const GROUND_SCATTER_TYPES = new Set<ResourceState['type']>(['berry', 'mushroom', 'purple_berry']);

/**
 * Draw-order comparator for the resource layer: ground-scatter types
 * (GROUND_SCATTER_TYPES) always draw before everything else, then within
 * each of those two groups it falls back to a plain ascending-y sort (the
 * usual top-down painter's algorithm).
 *
 * This has to be a strict two-tier split rather than "just force tree after
 * berry" — an asymmetric override only between those two types is not a
 * valid total order once a third type (say, rock) is in the mix: y alone
 * could put tree < rock < berry, while the forced rule says tree > berry,
 * a genuine cycle. Array.prototype.sort assumes a consistent order and
 * doesn't handle cycles gracefully — depending on the input array's exact
 * starting order (which shifts slightly every tick as the server resends
 * resources), it can resolve the contradiction differently frame to frame,
 * which is exactly what read as the berry flickering above/below its
 * neighbor as the player moved. Splitting into two tiers first (never
 * comparing across groups by y at all) removes the contradiction entirely.
 */
function resourceDrawOrder(a: ResourceState, b: ResourceState): number {
  const aScatter = GROUND_SCATTER_TYPES.has(a.type);
  const bScatter = GROUND_SCATTER_TYPES.has(b.type);
  if (aScatter !== bScatter) return aScatter ? -1 : 1;
  return a.y - b.y;
}

