    drawBlockShape(ctx, FOX_TAIL_TIP, FOX_CREAM_PALETTE, BLOCK);

    drawBlockShape(ctx, FOX_BODY, FOX_PALETTE, BLOCK);
    drawBlockShape(ctx, FOX_CHEST, FOX_CREAM_PALETTE, BLOCK);
