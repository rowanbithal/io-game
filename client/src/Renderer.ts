// Cell rects sharing a color are batched into one Path2D + one fill() call —
// filling adjoining rects individually can leave hairline anti-aliasing
// seams between them; filling them as one path does not.
function drawBlockShape(
  ctx: CanvasRenderingContext2D,
  cells: Cell[],
  palette: Palette3,
  block: number,
  offsetX = 0,
  offsetY = 0,
): void {
  const paths: Record<Shade, Path2D> = { light: new Path2D(), base: new Path2D(), dark: new Path2D() };
  for (const { gx, gy, shade } of cells) {
    paths[shade].rect(offsetX + gx * block - block / 2, offsetY + gy * block - block / 2, block, block);
  }
  for (const shade of ['dark', 'base', 'light'] as const) {
    ctx.fillStyle = palette[shade];
    ctx.fill(paths[shade]);
  }
}

