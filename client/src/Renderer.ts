  /**
   * Bakes one repeating ground tile using the biome-scale value-noise blend
   * (see the section header above `buildLattice`): two independent 4×4
   * lattices decide a base light<->dark shade band and, if `accent` is
   * given, where a fourth "dry"/mossy accent color breaks out of the
   * lightest band. Grass uses `accent` for its yellow patches; the forest
   * floor tiles skip it and just get the three-tone shade blend plus
   * speckle, since "dry patch" isn't a meaningful idea for bare dirt.
   */
  private bakeGroundTile(
    seed: number,
    shades: { dark: string; base: string; light: string },
    accent?: { color: string; shadeMin: number; dryMin: number },
  ): CanvasPattern | null {
    const tileBlocks = this.groundTileBlocks;
    const size = tileBlocks * BLOCK;
    const pat = document.createElement('canvas');
    pat.width = size;
    pat.height = size;
    const pc = pat.getContext('2d')!;
    pc.imageSmoothingEnabled = false;

    const rng = mulberry32(seed); // deterministic RNG so the pattern is seamless

    const latticeSize = 4;
    const patchScale = tileBlocks / latticeSize;
    const shadeLattice = buildLattice(latticeSize, rng);
    const dryLattice = buildLattice(latticeSize, rng).map((row) => row.map((v) => v * v)); // skew low — the accent is the exception

    for (let gy = 0; gy < tileBlocks; gy++) {
      for (let gx = 0; gx < tileBlocks; gx++) {
        // Jitter the sampled values per-block before thresholding — a pure
        // hash of the block coords, not a stream RNG call, so it's stable
        // and seamless across the tile wrap. The underlying noise field
        // still shapes the region at large scale, but right at a boundary
        // this scrambles individual blocks back and forth across the
        // threshold, giving a messy, speckled edge instead of one clean
        // curve — while every block is still a single flat color.
        const shadeJ = hashCell(gx, gy, seed + 7) / 4294967295 - 0.5;
        const dryJ = hashCell(gx, gy, seed + 8) / 4294967295 - 0.5;
        const shade = sampleLattice(shadeLattice, latticeSize, patchScale, gx, gy) + shadeJ * 0.16;
        const dryness = sampleLattice(dryLattice, latticeSize, patchScale, gx, gy) + dryJ * 0.16;

        // The accent only grows out of the light band — never the mid or
        // dark bands — so it never spawns inside shaded patches.
        if (accent && shade >= accent.shadeMin && dryness > accent.dryMin) pc.fillStyle = accent.color;
        else if (shade < 0.38) pc.fillStyle = shades.dark;
        else if (shade < 0.62) pc.fillStyle = shades.base;
        else pc.fillStyle = shades.light;

        pc.fillRect(gx * BLOCK, gy * BLOCK, BLOCK, BLOCK);
      }
    }

    // Fine speckle on top, for subtle texture within the smooth blend.
    pc.globalAlpha = 0.3;
    for (let gy = 0; gy < tileBlocks; gy++) {
      for (let gx = 0; gx < tileBlocks; gx++) {
        const roll = rng();
        if (roll < 0.035) pc.fillStyle = shades.dark;
        else if (roll < 0.06) pc.fillStyle = shades.light;
        else continue;
        pc.fillRect(gx * BLOCK, gy * BLOCK, BLOCK, BLOCK);
      }
    }
    pc.globalAlpha = 1;

    return this.ctx.createPattern(pat, 'repeat');
  }

  private buildGroundPattern(): void {
    this.groundPattern = this.bakeGroundTile(
      42,
      { dark: P.grassB, base: P.grassA, light: P.grassLight },
      { color: P.grassYellow, shadeMin: 0.62, dryMin: 0.55 },
    );
    this.dirtGroundPattern = this.bakeGroundTile(43, { dark: P.dirtDark, base: P.dirt, light: P.dirtLight });
    this.buildGrassShadeLattice();
  }

  /**
   * Rebuilds just the shade lattice the grass tile above was baked from —
   * same seed (42) and same draw order as bakeGroundTile's own internal
   * lattice, so this is bit-for-bit the array that produced the visible
   * grass pattern. sampleGrassShade uses it to look up that exact value in
   * real time for the forest-edge blend (see "Shaded grass approaching the
   * forest").
   */
  private buildGrassShadeLattice(): void {
    const rng = mulberry32(42);
    this.grassShadeLattice = buildLattice(this.grassLatticeSize, rng);
  }

  /** The plains grass tile's own shade value (0..1) at a given block — see buildGrassShadeLattice. */
  private sampleGrassShade(gx: number, gy: number): number {
    const patchScale = this.groundTileBlocks / this.grassLatticeSize;
    const jitter = hashCell(gx, gy, 42 + 7) / 4294967295 - 0.5;
    return sampleLattice(this.grassShadeLattice, this.grassLatticeSize, patchScale, gx, gy) + jitter * 0.16;
  }

