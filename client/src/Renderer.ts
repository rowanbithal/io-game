// ── Block-sprite engine ─────────────────────────────────────────────────────
// Every sprite is built from a grid of square "blocks" instead of arcs or
// gradients, so the chunky pixel-art look comes from the actual shapes being
// drawn, not from a downscale/upscale filter over smooth art.

const BLOCK = 5; // World units per block — bump this up for chunkier sprites.
// Trees/rocks are each drawn on their own pixel grid sized to their SPAN
// (world-unit footprint), so a resource renders as an integer number of
// BLOCKs across — its own footprint's edges always line up with a
// contiguous neighbor's, regardless of the fine placement GRID_CELL.
const TREE_PIXELS = TREE_SPAN / BLOCK;
const ROCK_PIXELS = ROCK_SPAN / BLOCK;
const GOLD_PIXELS = GOLD_SPAN / BLOCK;
const DIAMOND_PIXELS = DIAMOND_SPAN / BLOCK;
// Wheat uses its own, finer pixel size — individual strands need to read as
// distinct marks, which the main BLOCK is too coarse to show at wheat's
// small clump footprint.
const WHEAT_BLOCK = BLOCK / 2;

type Shade = 'light' | 'base' | 'dark';
type Cell = { gx: number; gy: number; shade: Shade };
type Palette3 = Record<Shade, string>;

/** A filled circle of blocks, shaded in horizontal bands (top/mid/bottom). */
function blockCircle(radiusBlocks: number, aspectX = 1): Cell[] {
  const cells: Cell[] = [];
  const topBand = -Math.round(radiusBlocks * 0.35);
  const bottomBand = Math.round(radiusBlocks * 0.45);
  const rx = Math.ceil(radiusBlocks * aspectX);
  for (let gy = -radiusBlocks; gy <= radiusBlocks; gy++) {
    for (let gx = -rx; gx <= rx; gx++) {
      if (Math.hypot(gx / aspectX, gy) > radiusBlocks + 0.15) continue;
      const shade: Shade = gy <= topBand ? 'light' : gy >= bottomBand ? 'dark' : 'base';
      cells.push({ gx, gy, shade });
    }
  }
  return cells;
}

// ── Biome-scale ground blending ──────────────────────────────────────────────
// A small lattice of random values, smoothly interpolated (classic 2D value
// noise) rather than stamped as discrete blobs — that's what makes regions
// merge into their neighbors with organic, wavy boundaries instead of
// looking like stamped circles. The *values* interpolate smoothly, but each
// block still gets snapped to one flat palette color (see buildGroundPattern)
// — no per-pixel gradient, just smoothly-shaped edges between flat colors.
// The lattice wraps with modulo indexing, so it tiles seamlessly.

/** Builds a `size`×`size` wrapping lattice of random values in [0, 1). */
function buildLattice(size: number, rng: () => number): number[][] {
  const lattice: number[][] = [];
  for (let y = 0; y < size; y++) {
    const row: number[] = [];
    for (let x = 0; x < size; x++) row.push(rng());
    lattice.push(row);
  }
  return lattice;
}

/** Smoothly samples a wrapping lattice at fractional block position (gx, gy). */
function sampleLattice(lattice: number[][], size: number, scale: number, gx: number, gy: number): number {
  const fx = gx / scale;
  const fy = gy / scale;
  const ix0 = Math.floor(fx) % size;
  const iy0 = Math.floor(fy) % size;
  const ix1 = (ix0 + 1) % size;
  const iy1 = (iy0 + 1) % size;
  const tx = smoothstep(fx - Math.floor(fx));
  const ty = smoothstep(fy - Math.floor(fy));
  const top = lattice[iy0][ix0] + (lattice[iy0][ix1] - lattice[iy0][ix0]) * tx;
  const bottom = lattice[iy1][ix0] + (lattice[iy1][ix1] - lattice[iy1][ix0]) * tx;
  return top + (bottom - top) * ty;
}

// ── Dark forest biome ────────────────────────────────────────────────────────
// The biome averages the top third of the map (y < DARK_FOREST_BAND), but its
// actual edge wanders per world x — see darkForestBandAt, which sums a few
// sine waves the same way lakeHarmonics gives a lake's coastline real coves
// instead of a bumpy circle. Everything below is a pure function of (x, y),
// computed identically server- and client-side, so no biome data (or the
// meander itself) needs to cross the wire.

/** Stable per-block random in [0, 1). */
function blockRandom(gx: number, gy: number, salt: number): number {
  return hashCell(gx, gy, salt) / 4294967295;
}

/**
 * Fine roughness added on top of the coarse sine-wave meander — the same
 * "coarse harmonics plus fine per-cell jitter" layering lakeWaterCells uses,
 * with the "fine" part a per-block hash (stable across frames, unlike a
 * stream RNG) and the "coarse" part a short-wavelength sine rather than a
 * hash bucketed onto a wider grid. That distinction matters: an earlier
 * version bucketed the coarse term onto 9-block cells, which is constant
 * within each cell and jumps to a new constant next door — a real 45-unit
 * square baked into the wobble. Sine has no such grid to jump between; the
 * whole point of a wave over a hash here is that it stays continuous.
 */
const FOREST_FINE_WOBBLE_RANGE = 130;

function forestEdgeWobble(gx: number, gy: number): number {
  const fine = blockRandom(gx, gy, 91) - 0.5;
  const wave = Math.sin((gx * BLOCK) / 55 + (gy * BLOCK) / 70) * 0.5;
  return (fine * 0.3 + wave * 0.7) * FOREST_FINE_WOBBLE_RANGE;
}

/** Sea coastline's own fine wobble — same construction as forestEdgeWobble, own salt/wavelengths so it doesn't echo the forest edge's exact texture. */
const SEA_FINE_WOBBLE_RANGE = 90;

function seaEdgeWobble(gx: number, gy: number): number {
  const fine = blockRandom(gx, gy, 173) - 0.5;
  const wave = Math.sin((gx * BLOCK) / 48 + (gy * BLOCK) / 63) * 0.5;
  return (fine * 0.3 + wave * 0.7) * SEA_FINE_WOBBLE_RANGE;
}

/**
 * Desert border's own fine wobble — same construction again, but perturbing
 * the boundary's x rather than its y (the desert is a vertical band, so its
 * edge wanders per world y instead of per world x — see desertBandAt).
 */
const DESERT_FINE_WOBBLE_RANGE = 100;

function desertEdgeWobble(gx: number, gy: number): number {
  const fine = blockRandom(gx, gy, 233) - 0.5;
  const wave = Math.sin((gx * BLOCK) / 50 + (gy * BLOCK) / 65) * 0.5;
  return (fine * 0.3 + wave * 0.7) * DESERT_FINE_WOBBLE_RANGE;
}

/** Densest the desert's blend fringe gets, right at the solid sand edge — see drawDesertGround. */
const DESERT_BLEND_MAX = 0.55;

/**
 * Dune shade at a continuous value, dithered between neighboring tones
 * rather than snapped at a hard threshold — the same per-block dithering
 * trick pickRampIndex uses for the forest's grass ramp, applied to just
 * three bands instead of five. `dune` runs roughly -0.7..0.7 (the sum of the
 * two sine amplitudes in drawDesertGround); mid-crest and mid-trough read as
 * solid dark/light, but each crossing between bands blurs into a speckled
 * few blocks instead of a single hard edge, so the wave pattern reads as
 * smoothly graded rather than a flat-color patchwork.
 */
function duneShade(dune: number, gx: number, gy: number): Shade {
  const position = clamp01((dune + 0.7) / 1.4) * 2; // 0 = dark, 1 = base, 2 = light
  const i0 = Math.min(1, Math.floor(position));
  const frac = position - i0;
  const idx = blockRandom(gx, gy, 618) < frac ? i0 + 1 : i0;
  return idx <= 0 ? 'dark' : idx >= 2 ? 'light' : 'base';
}

/**
 * How far into the forest floor a given block sits: 0 out on the plains, 1
 * from the (locally wavy) band edge northward. Linear rather than eased —
 * across a seam this narrow, a smoothstep just wastes most of the width
 * barely changing. `seamEnd` is the dirt seam's outer edge for this block's
 * column (band edge + DARK_FOREST_TRANSITION), already including wobble.
 */
function forestFloorDepth(seamEnd: number, worldY: number): number {
  return clamp01((seamEnd - worldY) / DARK_FOREST_TRANSITION);
}

// ── Forest floor seam ────────────────────────────────────────────────────────
// Built the way a lake's shore meets the grass (see lakeShoreCells), not the
// way the plains blend their own grass tones. That distinction is the whole
// look: the plains mix by thresholding noise everywhere, so no color ever
// owns a solid area. A shore instead reads as *solid* material with one
// ragged edge, and only past that edge does it break up into sparse speckle
// thinning out into whatever's behind it. The forest floor does the same —
// solid color bands with torn edges, then a speckled fringe — and chains four
// of them (dirt, then three grass shades) into one continuous ladder.

/**
 * Depth past which the floor is solid dirt; below it, the speckled fringe.
 * Set high so the fringe owns most of the seam — that speckled stretch, where
 * dirt and the innermost grass ring interleave, is the part worth looking at.
 */
const FLOOR_SOLID_DEPTH = 0.78;
/** How ragged the solid dirt's edge is, in depth units — a couple of blocks' worth. */
const FLOOR_EDGE_JITTER = 0.14;
/** Densest the fringe gets, right at the solid edge (the lake shore uses 0.5 too). */
const FLOOR_FRINGE_MAX = 0.62;

/**
 * Whether a block is dirt rather than grass. Solid dirt up to a per-block
 * jittered edge, then sparse dirt speckle thinning out into the grass —
 * the same two-part shape, and the same `(1 - t) * 0.5` falloff, that
 * lakeShoreCells uses to break its sand ring up into the surrounding grass.
 */
function isForestFloorBlock(depth: number, gx: number, gy: number): boolean {
  const jitter = (blockRandom(gx, gy, 93) - 0.5) * FLOOR_EDGE_JITTER;
  if (depth + jitter >= FLOOR_SOLID_DEPTH) return true;

  const t = (FLOOR_SOLID_DEPTH - depth) / FLOOR_SOLID_DEPTH;
  if (t > 1 || t < 0) return false;
  return blockRandom(gx, gy, 94) < (1 - t) * FLOOR_FRINGE_MAX;
}

// ── Shaded grass approaching the forest ──────────────────────────────────────
// An earlier version painted this as a few discrete tiles (outer/mid/inner
// rings), each its own independently-seeded noise pattern. That was the bug:
// two textures generated from unrelated random fields don't blend just
// because they're both green — the plains grass tile shows one pattern, and
// the ring tile shows a completely different one, so wherever they met (or
// handed off to each other) the mismatch read as a visible seam, not a blend.
//
// This instead reuses the EXACT SAME shade value the plains tile itself is
// baked from (see sampleGrassShade) and just pushes it toward the dark end of
// one continuous 5-stop ramp as the forest gets closer. Since every block's
// color comes from the same underlying field the plains already use, a block
// right next to the true edge is (at zero darkening) indistinguishable from
// what the baked tile would have shown there anyway — the "seam" disappears
// because there's only ever one texture, not two trying to agree.

/** Ramp from the darkest forest-adjacent tone to the plains' own lightest — index 0..4. */
const FOREST_GRASS_RAMP = [P.grassShadowDark, P.grassShadow, P.grassB, P.grassA, P.grassLight];
/** World units south of the true (wavy) edge the darkening takes to fade out. */
const FOREST_GRASS_REACH = 340;

/** How strongly grass darkens toward the forest at a given world y, 0..1 — 1 right at the edge. */
function forestGrassDarkening(bandY: number, worldY: number): number {
  return smoothstep(clamp01((bandY + FOREST_GRASS_REACH - worldY) / FOREST_GRASS_REACH));
}

/**
 * Which ramp stop a shade value would be at zero darkening — the exact same
 * thresholds bakeGroundTile itself uses to choose dark/base/light, so this
 * is an index, not an approximation of one.
 */
function plainsRampIndex(shade: number): number {
  if (shade < 0.38) return 2; // grassB
  if (shade < 0.62) return 3; // grassA
  return 4; // grassLight
}

/**
 * Where a block sits on FOREST_GRASS_RAMP, continuous. Scaling the block's
 * own plains index by (1 - darkening) rather than remapping shade across the
 * whole ramp from scratch is what makes darkening=0 land exactly on that
 * block's plains index (index * 1 = index, a whole number — see
 * pickRampIndex) while still sliding smoothly down through the intermediate
 * stops as darkening rises to 1 (index 0).
 */
function forestRampPosition(shade: number, darkening: number): number {
  return plainsRampIndex(shade) * (1 - darkening);
}

/** How much `sharpenFrac` narrows the noisy near-50/50 band — 1 = off, higher = narrower. */
const FOREST_RAMP_CONTRAST = 1.6;

/**
 * Pulls `frac` away from 0.5 toward whichever end it's already closer to —
 * only the stretch immediately around 0.5 is genuine ~50/50 speckle (the
 * noisiest-looking part of any random dither); everywhere else this settles
 * toward one solid color sooner than a straight linear fade would. Narrows
 * how much of the gradient looks actively speckled at once, without changing
 * the two colors involved or how far the gradient physically reaches.
 */
function sharpenFrac(frac: number): number {
  return clamp01((frac - 0.5) * FOREST_RAMP_CONTRAST + 0.5);
}

/**
 * Rounds a continuous ramp position down to one of the ramp's actual flat
 * colors — by dithering between its two nearest stops, weighted by how close
 * it sits to each, rather than blending their RGB values together.
 *
 * An earlier version did blend the RGB — mathematically the right endpoints,
 * but wrong in kind: nothing else in this game blends by mixing colors.
 * Every other transition here (sand into grass, dirt into grass) blends by
 * *speckle density* between a small set of fixed flat colors, and it's that
 * density-based dithering, not color accuracy, that reads as pixel art. The
 * per-block roll is a plain random one (not ordered/Bayer) — same speckled,
 * grainy character as the rest of the game's fades.
 *
 * At darkening=0, `position` is an exact integer (see forestRampPosition),
 * so frac=0 and this always returns i0 — the block's real plains color, with
 * total certainty, not just on average.
 */
function pickRampIndex(position: number, gx: number, gy: number): number {
  const clamped = Math.max(0, Math.min(FOREST_GRASS_RAMP.length - 1, position));
  const i0 = Math.floor(clamped);
  const i1 = Math.min(FOREST_GRASS_RAMP.length - 1, i0 + 1);
  const frac = sharpenFrac(clamped - i0);
  return blockRandom(gx, gy, 98) < frac ? i1 : i0;
}

// ── Dark forest night vignette ───────────────────────────────────────────────
// A pixelated black vignette that closes in from the edges of the screen as
// night falls over the dark forest — heavier the deeper into the biome you
// are, heaviest up around the gold (GOLD_TOP_BAND) — leaving only a circular
// window of clear vision centered on the player, like a torchlit ring in the
// dark. Anchored to the viewport rather than the world: unlike the old
// patchy mist this replaced, it doesn't drift or bank with the terrain, it
// just radiates out from the middle of the screen and fades in and out with
// the night.
//
// Built the way every other gradient here is — never a smooth alpha ramp,
// but a handful of fixed opacity steps on a chunky block grid, dithered
// between neighbouring steps by a stable per-block roll (the same trick
// pickRampIndex uses on the ground). That dithering is what keeps it
// reading as pixel art instead of an airbrushed wash over the scene.

/** Chunkier than the sprite grid, for the same reason GLOW_BLOCK is: the vignette is soft, not detailed. */
const FOG_BLOCK = BLOCK * 3;

/**
 * Opacity steps. Index 0 is clear; the top one is a near-opaque black —
 * deep night in the dark forest should genuinely blind the corners of the
 * screen, not just tint them. Finer-grained than a typical stepped ramp on
 * purpose: pickFogStep dithers between adjacent steps by flipping individual
 * blocks on ahead of their neighbours, and with only a few big steps that
 * dithering reads as scattered, high-contrast flecks popping in across the
 * screen the moment the vignette starts to show. More, smaller steps keep
 * each early flip subtle enough that the vignette reads as a smooth fade-in
 * instead of noise arriving before the fog does.
 */
const FOG_STEPS = [0, 0.06, 0.13, 0.22, 0.32, 0.44, 0.58, 0.73, 0.9];

/** How far past the tree line the vignette still reaches, so it eases in rather than starting on a line. */
const FOG_EDGE_FEATHER = 260;

/**
 * Radius of the fully-clear circle at the center of the screen, as a
 * fraction of the corner distance (half the screen diagonal). Small, so the
 * clear window reads as a tight ring of vision around the player rather
 * than most of the screen.
 */
const FOG_VIGNETTE_CLEAR = 0.22;

/**
 * Radius at which the vignette hits full opacity, as a fraction of the
 * corner distance. Past this the whole screen — corners included — is flat
 * at the top FOG_STEPS value; between FOG_VIGNETTE_CLEAR and this is the
 * gradient ring where the darkness fades in.
 */
const FOG_VIGNETTE_FULL = 0.7;

/** Furthest south any vignette reaches, for a cheap whole-frame early-out. */
const FOG_MAX_Y = DARK_FOREST_BAND + DARK_FOREST_EDGE_AMPLITUDE + FOG_EDGE_FEATHER;

/**
 * How heavy the vignette gets at this depth into the biome, 0..1, before
 * night is factored in: 0 out at the feathered edge, 1 by the time you're up at the gold.
 */
function forestFogDepth(bandY: number, worldY: number): number {
  const start = bandY + FOG_EDGE_FEATHER;
  return smoothstep(clamp01((start - worldY) / (start - GOLD_TOP_BAND)));
}

/**
 * Which opacity step a block lands on, dithered between the two it falls
 * between. Deliberately doesn't sharpen the fraction the way the ground ramp
 * does: a grass seam wants a crisp boundary, a vignette wants a diffuse one.
 */
function pickFogStep(density: number, gx: number, gy: number): number {
  const scaled = clamp01(density) * (FOG_STEPS.length - 1);
  const step = Math.floor(scaled);
  const next = Math.min(FOG_STEPS.length - 1, step + 1);
  return blockRandom(gx, gy, 151) < scaled - step ? next : step;
}

// forestFactor / isForestTree / isForestRock now live in shared/biome.ts —
// the server needs the identical answer to pay out an oversized forest
// tree's or boulder's larger yield (see resourceSizeScale).

// ── Top-down tree / rock silhouettes ────────────────────────────────────────
// Each tree is its own rounded crown (leaves a gap to the cell edge — see
// BRANCH_* below, which bridges that gap between orthogonally-connected
// trees). Rocks get a more angular, directionally-shaded mask and don't
// need to touch their neighbors.

/** A round, jagged-edged canopy viewed from above, shaded light→dark from center out. */
function treeCrownCells(seed: number): Cell[] {
  const rng = mulberry32(seed);
  const n = TREE_PIXELS;
  const center = (n - 1) / 2;
  const maxR = center * (0.85 + rng() * 0.3); // large canopy — may just reach/graze the cell edge
  const cells: Cell[] = [];
  for (let py = 0; py < n; py++) {
    for (let px = 0; px < n; px++) {
      const dx = px - center;
      const dy = py - center;
      const d = Math.hypot(dx, dy);
      const jitter = (rng() - 0.5) * 1.3; // irregular, "varying rectangular" outline
      if (d > maxR + jitter) continue;
      const shade: Shade = d < maxR * 0.4 ? 'light' : d > maxR * 0.78 ? 'dark' : 'base';
      cells.push({ gx: dx, gy: dy, shade });
    }
  }
  return cells;
}

/**
 * A compact, angular boulder mask with directional (upper-left) light/shadow
 * faces, at `n` pixels across. Shared by rock (ROCK_PIXELS) and gold
 * (GOLD_PIXELS) — gold is the same boulder shape, just bigger and recolored
 * (see goldPatchCells/GOLD_PALETTE), so a deposit reads unmistakably as "a
 * rock, but gold" rather than an unrelated shape.
 */
function boulderCells(seed: number, n: number): Cell[] {
  const rng = mulberry32(seed);
  const center = (n - 1) / 2;
  const maxR = center * (0.65 + rng() * 0.3); // big, chunky boulder
  const cells: Cell[] = [];
  for (let py = 0; py < n; py++) {
    for (let px = 0; px < n; px++) {
      const dx = px - center;
      const dy = py - center;
      const d = Math.hypot(dx, dy);
      const jitter = (rng() - 0.5) * 1.6; // rockier, more angular edge than trees
      if (d > maxR + jitter) continue;
      const facing = -dx * 0.7 - dy * 0.7; // simulated light from the upper-left
      const shade: Shade = facing > maxR * 0.35 ? 'light' : facing < -maxR * 0.35 ? 'dark' : 'base';
      cells.push({ gx: dx, gy: dy, shade });
    }
  }
  return cells;
}

function rockPatchCells(seed: number): Cell[] {
  return boulderCells(seed, ROCK_PIXELS);
}

function goldPatchCells(seed: number): Cell[] {
  return boulderCells(seed, GOLD_PIXELS);
}

/** Same boulder shape again, at diamond's own (bigger) pixel size — see DIAMOND_PALETTE for the recolor. */
function diamondPatchCells(seed: number): Cell[] {
  return boulderCells(seed, DIAMOND_PIXELS);
}

/**
 * Small pebbles scattered loosely in a ring just outside any rock's own
 * footprint, plains or dark forest — purely decorative ground clutter, not a
 * resource of their own, so they carry no collision or harvest interaction.
 * Originally added just for dark forest rocks, to keep the forest floor from
 * reading too bare now that they're both sparser and no longer clustered
 * (see World.ts's DARK_FOREST_ROCK_CONFIG) — broadened to every rock since a
 * plains boulder sitting bare looked like the odd one out next to a forest
 * one ringed in pebbles. Positions are in the same `n`-pixel coordinate space
 * as the boulder cells above, so they scale with the rock's own render-time
 * block size (see FOREST_ROCK_SCALE) instead of needing their own.
 */
// `shade` gives pebble-to-pebble tone variety (see PEBBLE_PALETTE); each one
// also gets a small upper-left highlight at draw time (same simulated-light
// convention boulderCells uses) so an individual pebble reads as a tiny
// rounded stone rather than a flat tinted square.
interface Pebble { gx: number; gy: number; shade: Shade }

function rockPebbles(seed: number, n: number): Pebble[] {
  const rng = mulberry32(seed + 1); // independent stream from the boulder shape itself
  const center = (n - 1) / 2;
  const innerR = center * 0.95; // just outside the boulder's own edge
  const outerR = center * 1.8; // how far pebbles scatter beyond it
  const count = 2 + Math.floor(rng() * 3); // 2-4 pebbles
  const pebbles: Pebble[] = [];
  for (let i = 0; i < count; i++) {
    const angle = rng() * Math.PI * 2;
    const r = innerR + rng() * (outerR - innerR);
    const shadeRoll = rng();
    const shade: Shade = shadeRoll < 0.3 ? 'dark' : shadeRoll < 0.55 ? 'light' : 'base';
    pebbles.push({ gx: Math.cos(angle) * r, gy: Math.sin(angle) * r, shade });
  }
  return pebbles;
}

/**
 * Fallen-leaf litter scattered in a ring just outside any tree's own crown,
 * plains or dark forest — the tree counterpart to rockPebbles above, but
 * built from whole leafCells glyphs (see the ground clutter section below)
 * rather than flat tinted squares, so the leaves lying under a tree are
 * unmistakably the same leaves scattered loose in the grass a few steps
 * away, just naturally more common near their source.
 *
 * Returned as clusters — a ring position plus that leaf's own local cells —
 * rather than one flattened Cell[], because the two need different scales
 * applied at draw time (see drawTreeLeafLitter): the ring itself has to sit
 * at a full-size radius outside the canopy, but each individual leaf has to
 * render much smaller than a crown pixel or it just reads as another patch
 * of crown-sized blocks. A single drawBlockShape call only has one block
 * size to give it, which can't satisfy both at once — keeping the ring
 * position and the glyph's own cells separate is what lets the draw call
 * scale them independently.
 */
interface LeafLitterCluster { ox: number; oy: number; cells: Cell[] }

function treeLeafLitterClusters(seed: number, n: number): LeafLitterCluster[] {
  const rng = mulberry32(seed + 2); // independent stream from both the crown shape and any pebble stream
  const center = (n - 1) / 2;
  const innerR = center * 0.95; // just outside the crown's own edge
  const outerR = center * 1.5; // how far leaves scatter beyond it
  const count = 4 + Math.floor(rng() * 4); // 4-7 leaves
  const clusters: LeafLitterCluster[] = [];
  for (let i = 0; i < count; i++) {
    const angle = rng() * Math.PI * 2;
    const r = innerR + rng() * (outerR - innerR);
    clusters.push({ ox: Math.cos(angle) * r, oy: Math.sin(angle) * r, cells: leafCells(rng) });
  }
  return clusters;
}

/**
 * Individual wheat strands — sparse, not a solid fill — each a tall blade
 * (a golden grain head with a stem trailing down beneath it, darkening
 * toward the base) scattered within the clump's footprint, at WHEAT_BLOCK
 * resolution. Leaving gaps between strands (rather than the tiled full-cell
 * fill trees/rocks use) is what makes each plant read as its own stalk,
 * with the ground showing through around it, same as a real field looks
 * from above. Blades run long enough to spill past their own clump into
 * neighboring ones — clumps in a field are placed touching, so this reads
 * as one shaggy patch of long grass rather than a grid of short tufts.
 */
// Minimum gap (in WHEAT_BLOCK cells) kept between strand columns — without
// this, random placement occasionally drops two blades close enough to
// merge into one thick clump instead of reading as separate stalks.
const WHEAT_STRAND_SPACING = 1.3;
const WHEAT_PLACEMENT_ATTEMPTS = 8;

function wheatCells(seed: number): Cell[] {
  const rng = mulberry32(seed);
  const halfBlocks = WHEAT_SPAN / WHEAT_BLOCK / 2;
  const inset = halfBlocks - 1.5; // keep strand heads off the very edge of the clump
  const count = 9 + Math.floor(rng() * 5); // 9-13 strands per clump
  const cells: Cell[] = [];
  const placed: { gx: number; gy: number }[] = [];

  for (let i = 0; i < count; i++) {
    let gx = 0;
    let gy = 0;
    // A few retries to find a spot clear of existing strands; if none pan
    // out, just take the last roll rather than thinning the clump out.
    for (let attempt = 0; attempt < WHEAT_PLACEMENT_ATTEMPTS; attempt++) {
      gx = (rng() * 2 - 1) * inset;
      gy = (rng() * 2 - 1) * inset;
      const clear = placed.every((p) => Math.hypot(gx - p.gx, gy - p.gy) >= WHEAT_STRAND_SPACING);
      if (clear) break;
    }
    placed.push({ gx, gy });

    const length = 6 + Math.floor(rng() * 6); // 6-11 cells tall, well beyond the old fixed 2
    const headShade: Shade = rng() < 0.35 ? 'light' : 'base';
    cells.push({ gx, gy, shade: headShade }); // grain head
    for (let j = 1; j < length; j++) {
      // Stays 'base' near the head, then darkens toward the base of the
      // blade, so the extra length reads as a stem trailing off rather than
      // a uniform bar.
      const shade: Shade = j < length * 0.4 ? 'base' : 'dark';
      cells.push({ gx, gy: gy + j, shade });
    }
  }
  return cells;
}

// ── Lakes ─────────────────────────────────────────────────────────────────────
// A lake's outline isn't a jittered circle — its radius varies with angle
// (a few random sine harmonics summed together), giving real coves, bays,
// and inlets instead of just a bumpy circle. Water and shore share the same
// harmonics (computed once per lake) so the sand ring hugs the water's
// actual irregular coastline at a roughly constant width, rather than being
// its own independently-wobbly ring.

export interface LakeHarmonic { freq: number; amp: number; phase: number }

export function lakeHarmonics(seed: number): LakeHarmonic[] {
  const rng = mulberry32(seed);
  return [
    { freq: 2 + Math.floor(rng() * 2), amp: 0.12 + rng() * 0.1, phase: rng() * Math.PI * 2 },
    { freq: 3 + Math.floor(rng() * 3), amp: 0.07 + rng() * 0.06, phase: rng() * Math.PI * 2 },
    { freq: 6 + Math.floor(rng() * 4), amp: 0.03 + rng() * 0.04, phase: rng() * Math.PI * 2 },
  ];
}

/** Water's own radius at a given angle — the coastline before any shore is added. */
export function lobeRadius(theta: number, baseRadius: number, harmonics: LakeHarmonic[]): number {
  let r = baseRadius;
  for (const h of harmonics) r += baseRadius * h.amp * Math.sin(h.freq * theta + h.phase);
  return r;
}

/** Deep water at the center, shading to shallow near the coastline. */
function lakeWaterCells(seed: number, radiusBlocks: number, harmonics: LakeHarmonic[]): Cell[] {
  const rng = mulberry32(seed);
  const fineJitter = Math.max(1, radiusBlocks * 0.05); // fine roughness on top of the lobe shape
  const reach = Math.ceil(radiusBlocks * 1.6); // covers the largest possible lobe bulge
  const cells: Cell[] = [];
  for (let gy = -reach; gy <= reach; gy++) {
    for (let gx = -reach; gx <= reach; gx++) {
      const d = Math.hypot(gx, gy);
      const r = lobeRadius(Math.atan2(gy, gx), radiusBlocks, harmonics);
      const jitter = (rng() - 0.5) * fineJitter;
      if (d > r + jitter) continue;
      const shade: Shade = d < radiusBlocks * 0.5 ? 'dark' : d > radiusBlocks * 0.85 ? 'light' : 'base';
      cells.push({ gx, gy, shade });
    }
  }
  return cells;
}

type ShoreCell = { gx: number; gy: number; shade: Shade; pebble: boolean };

/**
 * Sand ring following the water's actual coastline at a roughly constant
 * width — wetter near the water, drier further out, with scattered pebbles.
 * Beyond the solid ring, sparse sand speckle fades out with distance
 * (dithered, like the ground's biome-patch boundaries) so the sand blends
 * into the surrounding grass instead of stopping at one hard edge.
 */
function lakeShoreCells(seed: number, waterRadiusBlocks: number, shoreWidthBlocks: number, harmonics: LakeHarmonic[]): ShoreCell[] {
  const rng = mulberry32(seed);
  const pebbleRng = mulberry32(seed + 1); // independent stream — doesn't disturb the jitter sequence above
  const blendRng = mulberry32(seed + 2); // independent stream for the fade-out speckle
  const fineJitter = Math.max(1, shoreWidthBlocks * 0.2);
  const blendWidth = Math.max(2, shoreWidthBlocks * 0.7); // how far the sand speckle fades into the grass
  const reach = Math.ceil(waterRadiusBlocks * 1.6 + (shoreWidthBlocks + blendWidth) * 1.2);
  const cells: ShoreCell[] = [];
  for (let gy = -reach; gy <= reach; gy++) {
    for (let gx = -reach; gx <= reach; gx++) {
      const d = Math.hypot(gx, gy);
      const waterR = lobeRadius(Math.atan2(gy, gx), waterRadiusBlocks, harmonics);
      const outerR = waterR + shoreWidthBlocks;
      const jitter = (rng() - 0.5) * fineJitter;
      const pebbleRoll = pebbleRng();
      const solidEdge = outerR + jitter;

      if (d > solidEdge) {
        // Past the solid shore: thin out sparse sand speckle over blendWidth,
        // leaving grass showing through more and more as distance grows.
        const t = (d - solidEdge) / blendWidth;
        if (t > 1 || blendRng() > (1 - t) * 0.5) continue;
        cells.push({ gx, gy, shade: 'light', pebble: false });
        continue;
      }

      const fromWater = d - waterR; // 0 at the water's edge, up to ~shoreWidth at the outer edge
      const shade: Shade = fromWater < shoreWidthBlocks * 0.35 ? 'dark' : fromWater > shoreWidthBlocks * 0.75 ? 'light' : 'base';
      cells.push({ gx, gy, shade, pebble: pebbleRoll < 0.06 });
    }
  }
  return cells;
}

function drawShoreShape(ctx: CanvasRenderingContext2D, cells: ShoreCell[], sand: Palette3, pebbleColor: string, block: number): void {
  const paths: Record<Shade, Path2D> = { light: new Path2D(), base: new Path2D(), dark: new Path2D() };
  const pebblePath = new Path2D();
  for (const { gx, gy, shade, pebble } of cells) {
    const rectX = gx * block - block / 2;
    const rectY = gy * block - block / 2;
    (pebble ? pebblePath : paths[shade]).rect(rectX, rectY, block, block);
  }
  for (const shade of ['dark', 'base', 'light'] as const) {
    ctx.fillStyle = sand[shade];
    ctx.fill(paths[shade]);
  }
  ctx.fillStyle = pebbleColor;
  ctx.fill(pebblePath);
}

